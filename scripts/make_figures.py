def fig_mechanism():
    text = read("PROP2_VALIDATION.md")
    hdr = next(r for r in rows(text) if r[0].startswith("benchmark"))
    data = [r for r in rows(text) if "/" in r[0] and r[0] != hdr[0]]
    ir, il = hdr.index("rho_w"), hdr.index("lost-correct risk")
    cls = {"gpqa_diamond": "four", "mmlu_pro": "ten"}
    pts = [(float(r[ir]), float(r[il]), cls.get(r[0].split("/")[0], "open"), r[0]) for r in data]
    groups = []
    for c in ("open", "ten", "four"):
        g = sorted((p for p in pts if p[2] == c), key=lambda p: (p[0], p[1]))
        toks = [f"({x:.3f},{y:.3f})[{c}]" for x, y, _, _ in g]
        groups += [toks[i:i + 4] for i in range(0, len(toks), 4)]
    lines = ["  " + " ".join(t.ljust(19) for t in g).rstrip() for g in groups]
    slope, icpt = np.polyfit([p[0] for p in pts], [p[1] for p in pts], 1)
    rho_s = float(re.search(r"Spearman\(P_spur, lost-correct risk\) = ([-+]\d\.\d+)", text).group(1))
