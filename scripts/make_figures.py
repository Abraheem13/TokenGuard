#!/usr/bin/env python
"""Write the TikZ/pgfplots source of every data figure from the result files.

Each figure reads its numbers from the committed files in experiments/ntc, so a
figure cannot drift from the data it plots. The thirteen data figures are
written to figures/src (or --out); the eight diagrams in figures/src are
authored by hand. figures/build.sh renders all of them to PDF.

    python scripts/make_figures.py [--out figures/src]
"""
from __future__ import annotations

import argparse
import json
