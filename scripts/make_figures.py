from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
NTC = ROOT / "experiments" / "ntc"
WORDS = ("zero one two three four five six seven eight nine ten eleven twelve thirteen "
         "fourteen fifteen sixteen seventeen eighteen nineteen").split()
TENS = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()


# ----------------------------------------------------------------- helpers
def read(name: str) -> str:
    return (NTC / name).read_text()


def rows(text, start=None):
    """Markdown table rows as lists of cells, from `start` to the next heading."""
    if start:
        i = text.index(start)
        j = text.find("\n## ", i + len(start))
        text = text[i:j if j > 0 else len(text)]
    return [[c.strip() for c in ln.strip().strip("|").split("|")]
            for ln in text.splitlines() if ln.startswith("|") and "---" not in ln]


def num(s):
    m = re.search(r"[-+]?\d*\.?\d+", str(s))
    return float(m.group()) if m else None


def words(n: int) -> str:
    if n < 20:
        return WORDS[n]
    t, u = divmod(n, 10)
    return TENS[t] + ("" if u == 0 else "-" + WORDS[u])


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def header(title: str, source: str) -> str:
    return f"% {title}\n% (generated by scripts/make_figures.py from experiments/ntc/{source})\n"


def slo_table():
    text = read("SLO_ATTAINMENT.md")
    hdr = next(r for r in rows(text) if r[0] == "setting")
    body = {r[0]: r for r in rows(text) if r[0] != "setting"}

    def deficit(setting, method):
        return float(body[setting][hdr.index(method)].split("(")[0].replace("+", ""))

    att = {}
    for ln in text.splitlines():
        m = re.match(r"- `([^`]+)`.*?within 1.0pt:\s*(\d+)%.*?within 2.5pt:\s*(\d+)%"
                     r".*?within 5.0pt:\s*(\d+)%", ln)
        if m:
            att[m.group(1)] = tuple(int(m.group(k)) for k in (2, 3, 4))
    return deficit, att


