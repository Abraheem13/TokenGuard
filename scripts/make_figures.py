def fig_kappa():
    tp = json.loads(read("TAIL_PRICE.json"))
    S, D = tp["settings"], tp["data"]

    def U(m, kap, worst=False):
        v = [D[m][s][1] - kap * max(0.0, -D[m][s][0]) for s in S]
        return min(v) if worst else sum(v) / len(v)

    CURVES = [("NTC-v2", "fusion tier", "accent", "solid"),
              ("NTC-full(e=0.05)", "selection tier", "midnavy", "dashed"),
              ("AGREE", "answer agreement", "brunelnavy", "dotted"),
              ("EAT", "entropy (EAT)", "textgrey", "densely dashdotted")]
    KAP = [0, 1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 25, 30]

    def panel(worst, title, ymin, ymax):
        body = []
        for key, lab, col, style in CURVES:
            p = " ".join(f"({k},{U(key, k, worst):.2f})" for k in KAP)
            body.append(f"\\addplot[draw={col},{style},line width=1.0pt] coordinates {{{p}}};\n"
                        f"\\addlegendentry{{{lab}}}")
        return ("\\begin{axis}[dissplot, height=5.4cm, width=6.6cm,\n"
                f"  title={{{title}}}, title style={{font=\\footnotesize\\itshape}},\n"
                "  xlabel={price of an accuracy point, $\\kappa$},\n"
                "  ylabel={utility (token-saving points)},\n"
                f"  xmin=0, xmax=30, ymin={ymin}, ymax={ymax}, grid=both,\n"
                "  axis x line*=bottom, axis y line*=left,\n"
                "  legend style={at={(0.03,0.03)},anchor=south west,font=\\scriptsize,\n"
                "                fill=white,fill opacity=0.85,text opacity=1,draw=rulegrey},\n"
                "  legend cell align=left]\n" + "\n".join(body) + "\n\\end{axis}")

    n = words(len(S))
    return (header("Utility against the price of an accuracy point", "TAIL_PRICE.json") +
            "\\begin{tikzpicture}\n" + panel(False, f"mean over the {n} settings", -60, 60) +
            "\n\\begin{scope}[xshift=7.4cm]\n" + panel(True, f"worst of the {n} settings", -160, 60) +
            "\n\\end{scope}\n\\end{tikzpicture}\n")


